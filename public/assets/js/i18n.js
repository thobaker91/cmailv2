export let lang = localStorage.getItem('cmail_lang') || (navigator.language?.startsWith('fa') ? 'fa' : 'en');

export function t(key) {
  return dict[lang]?.[key] ?? dict.en[key] ?? key;
}

export function setLang(l) {
  lang = l;
  localStorage.setItem('cmail_lang', l);
  applyLang();
}

export function applyLang() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.title = lang === 'fa' ? 'Cmail — صندوق ایمیل شیشه‌ای شما' : 'Cmail — your liquid-glass inbox';
}

applyLang();
