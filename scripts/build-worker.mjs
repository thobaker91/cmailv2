#!/usr/bin/env node
// Cmail — single-file worker build
// 1) embeds every file from public/ into src/generated/assets.ts
//    (the worker then serves its own UI — no "assets" binding, no folder upload)
// 2) turns schema.sql into src/generated/schema.ts (statement list for
//    the one-click "initialize tables" endpoint, plus healing ALTERs)
// 3) bundles src/worker.ts with esbuild → dist-worker/worker.js → root worker.js
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync, rmSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const PUB = join(ROOT, 'public');
const GEN = join(ROOT, 'src', 'generated');

// ---------- helpers ----------
const djb2 = (s) => {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return 'W/' + h.toString(36) + '-' + s.length.toString(36);
};

const TEXT_EXT = new Set(['.html', '.css', '.js', '.mjs', '.json', '.txt', '.svg', '.map']);
const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.map': 'application/json; charset=utf-8',
  '.woff2': 'font/woff2',
};

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// ---------- 1) embedded assets ----------
const APP_VERSION = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version ?? '0.0.0';

// ---------- module graph integrity ----------
// The entry script in index.html carries a version query (app.js?v=…). If the
// internal imports stayed bare ('./app.js'), the browser would treat the two
// URLs as two different modules: the whole shell booted twice — two
// hashchange listeners, two routers racing each other, views painted into
// detached nodes (the "inbox loads nothing / two sections open at once"
// bug family). Every relative import therefore gets the SAME version query,
// so the graph stays one single instance per release.
const VER = `?v=${APP_VERSION}`;
const stampImports = (code) => code
  // static: from './x.js'  /  import '../x.js'
  .replace(/(from\s+|import\s+)'((?:\.\.?\/)[^']*\.js)'/g, (_m, kw, spec) => `${kw}'${spec}${VER}'`)
  // dynamic: import('./x.js')
  .replace(/import\(\s*'((?:\.\.?\/)[^']*\.js)'\s*\)/g, (_m, spec) => `import('${spec}${VER}')`);

const files = walk(PUB);
const entries = [];
for (const p of files) {
  const key = relative(PUB, p).split('\\').join('/');
  const ext = extname(p).toLowerCase();
  const type = MIME[ext];
  if (!type) throw new Error(`no mime for ${key}`);
  let buf = readFileSync(p);
  // every release gets a fresh asset URL: the __CM_VER__ stamp in index.html
  // becomes the package version, so no browser can ever serve an old
  // app.js/app.css from its cache after an update
  if (key === 'index.html') {
    buf = Buffer.from(buf.toString('utf8').replaceAll('__CM_VER__', APP_VERSION), 'utf8');
  }
  if (ext === '.js' && key.startsWith('assets/js/')) {
    buf = Buffer.from(stampImports(buf.toString('utf8')), 'utf8');
  }
  const tag = djb2(buf.toString('latin1'));
  if (TEXT_EXT.has(ext)) {
    entries.push({ key, text: buf.toString('utf8'), type, tag });
  } else {
    entries.push({ key, b64: buf.toString('base64'), type, tag });
  }
}

mkdirSync(GEN, { recursive: true });
const assetsTs = `// AUTO-GENERATED by scripts/build-worker.mjs — do not edit by hand.
// Every UI file lives inside the worker: one paste, one binding, nothing else.
export type EmbeddedAsset = { text?: string; b64?: string; type: string; tag: string };

export const ASSET_FILES: Record<string, EmbeddedAsset> = {
${entries.map((e) => {
  const body = e.text !== undefined
    ? `text: ${JSON.stringify(e.text)}`
    : `b64: ${JSON.stringify(e.b64)}`;
  return `  ${JSON.stringify(e.key)}: { ${body}, type: ${JSON.stringify(e.type)}, tag: ${JSON.stringify(e.tag)} },`;
}).join('\n')}
};
`;
writeFileSync(join(GEN, 'assets.ts'), assetsTs);

// ---------- 2) schema statements ----------
// ORDER MATTERS: strip whole-line comments BEFORE splitting on ';'.
// Splitting first corrupts statements whenever a comment contains a
// semicolon or quote (real bug: "-- …original; preview is the" glued the
// fragment "preview is the" onto CREATE TABLE emails → init syntax error
// on fresh installs). A statement list that starts with prose is exactly
// how a deployed worker answers "internal server error" to the setup call.
const schemaSql = readFileSync(join(ROOT, 'schema.sql'), 'utf8');

const STMT_START = /^(CREATE|ALTER|DROP|INSERT|UPDATE|DELETE|REPLACE|BEGIN|COMMIT|VACUUM|ANALYZE|PRAGMA)\b/i;

// remove -- comments (whole-line AND trailing) without touching '…' literals
function stripSqlComments(raw) {
  let out = '';
  let inStr = false;
  for (let i = 0; i < raw.length; i++) {
    const ch = raw[i];
    if (inStr) {
      out += ch;
      if (ch === "'") {
        if (raw[i + 1] === "'") { out += "'"; i++; } // escaped ''
        else inStr = false;
      }
      continue;
    }
    if (ch === "'") { inStr = true; out += ch; continue; }
    if (ch === '-' && raw[i + 1] === '-') {
      while (i < raw.length && raw[i] !== '\n') i++;
      out += '\n';
      continue;
    }
    out += ch;
  }
  return out;
}

// split on ';' only outside string literals, validate every statement
function parseStatements(raw, label) {
  const text = stripSqlComments(raw);
  const stmts = [];
  let cur = '';
  let inStr = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    cur += ch;
    if (inStr) {
      if (ch === "'") {
        if (text[i + 1] === "'") { cur += "'"; i++; }
        else inStr = false;
      }
      continue;
    }
    if (ch === "'") { inStr = true; continue; }
    if (ch === ';') {
      const s = cur.trim();
      if (s.length > 1) stmts.push(s.slice(0, -1).trim());
      cur = '';
    }
  }
  const rest = cur.trim();
  if (rest) stmts.push(rest);
  return stmts.map((sql) => {
    if (!STMT_START.test(sql)) {
      throw new Error(
        `${label}: split produced a non-SQL statement — "${sql.slice(0, 70).replace(/\s+/g, ' ')}…"`
      );
    }
    return sql;
  });
}

const statements = parseStatements(schemaSql, 'schema.sql')
  .map((sql, i) => ({ name: `stmt_${String(i + 1).padStart(2, '0')}`, sql, optional: false }));

// healing statements: bring databases created by older releases up to date.
// they fail harmlessly ("duplicate column") on fresh installs → marked optional.
const healing = [];
for (const m of [
  'migrations/0002_mailbox_identity.sql',
  'migrations/0003_vault_folders.sql',
  'migrations/0005_domain_lifecycle.sql',
  'migrations/0006_vault_folder_scope.sql',
  'migrations/0007_mail_folders.sql',
  'migrations/0008_sent_mail.sql',
  'migrations/0009_share_access.sql',
  'migrations/0011_share_control.sql',
]) {
  let sql;
  try { sql = readFileSync(join(ROOT, m), 'utf8'); } catch { continue; }
  for (const st of parseStatements(sql, m)) {
    if (/^ALTER TABLE/i.test(st)) healing.push({ name: `heal_${healing.length + 1}`, sql: st, optional: true });
  }
}

const schemaTs = `// AUTO-GENERATED by scripts/build-worker.mjs — do not edit by hand.
// Full database schema: statements run in order by POST /api/setup/init.
// "optional" statements heal older installs and may fail harmlessly.
export type SchemaStatement = { name: string; sql: string; optional: boolean };

export const SCHEMA: SchemaStatement[] = [
${[...statements, ...healing]
  .map((s) => `  { name: ${JSON.stringify(s.name)}, optional: ${s.optional}, sql: ${JSON.stringify(s.sql)} },`)
  .join('\n')}
];
`;
writeFileSync(join(GEN, 'schema.ts'), schemaTs);

// ---------- 3) bundle ----------
rmSync(join(ROOT, 'dist-worker'), { recursive: true, force: true });
mkdirSync(join(ROOT, 'dist-worker'), { recursive: true });
execSync(
  'npx esbuild src/worker.ts --bundle --format=esm --target=es2022 --legal-comments=none --outfile=dist-worker/worker.js',
  { cwd: ROOT, stdio: 'inherit' },
);
copyFileSync(join(ROOT, 'dist-worker', 'worker.js'), join(ROOT, 'worker.js'));

const kb = (p) => (statSync(p).size / 1024).toFixed(1) + ' KB';
console.log('');
console.log('assets embedded :', entries.length, 'files');
console.log('schema stmts    :', statements.length, '+', healing.length, 'healing (optional)');
console.log('dist-worker     :', kb(join(ROOT, 'dist-worker/worker.js')));
console.log('root worker.js  :', kb(join(ROOT, 'worker.js')));
